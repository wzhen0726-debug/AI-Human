def rd(p):
    return io.open(p, encoding="utf-8").read()

def wr(p, s):
    io.open(p, "w", encoding="utf-8", newline="").write(s)

def sub(p, pairs):
    s = rd(p)
    for old, new in pairs:
        assert old in s, f"MISS in {os.path.basename(p)}: {old[:50]}"
        s = s.replace(old, new, 1)
    wr(p, s)
    print("  ✓ 更新", os.path.relpath(p, BASE))

def append(p, text):
    with io.open(p, "a", encoding="utf-8", newline="") as f:
        f.write(text.replace("\n", "\r\n"))
    print("  ✓ 追加", os.path.relpath(p, BASE))

def prepend(p, text):
    s = rd(p)
    wr(p, text + s)
    print("  ✓ 前缀", os.path.relpath(p, BASE))

